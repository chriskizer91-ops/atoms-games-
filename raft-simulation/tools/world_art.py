# Packs the painted world pictures (art/world/*.png) into src/art.js, sized for the game and stored inside the one file.
#   python3 tools/world_art.py
import base64, io, os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(HERE, '..', 'art', 'world')
def pack(name, size, crop=None, q=82):
    im = Image.open(os.path.join(SRC, name)).convert('RGB')
    if crop: im = im.crop(crop)
    im = im.resize(size, Image.LANCZOS); b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()
out = {
    # the sail is 1.4 m by 3.1 m: the middle strip of the painting, where its patches are
    'sail': pack('sail.png', (384, 850), (165, 0, 859, 1536)),
    'chart': pack('chart.png', (1200, 800), q=80),
    'note': pack('note.png', (640, 960), q=80),
    'flag': pack('flag.png', (512, 341)),
}
with open(os.path.join(HERE, '..', 'src', 'art.js'), 'w') as f:
    f.write('// GENERATED by tools/world_art.py from art/world/*.png: the painted sail, chart paper, note paper and flag.\n')
    f.write('export const ART = {\n' + ''.join("  %s: '%s',\n" % (k, v) for k, v in out.items()) + '};\n')
print({k: len(v) // 1024 for k, v in out.items()})
