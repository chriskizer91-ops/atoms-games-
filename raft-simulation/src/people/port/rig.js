// Step 2 of the port. Cuts the moving skeleton out of Moon Faire's jester_kit.js (three r128, a global script that also
// builds her whole costume and her spells) and writes it as src/people/kit/rig.js for three r186: the bones, the pose
// language, the two-bone limb solver, idle / walk / run, one-shot moves, and the repainting of the face. The lines are
// taken as they stand; the few changes are listed where they are made.
const fs = require('fs'), path = require('path');

module.exports = function rig(MF, OUT) {
  const L = fs.readFileSync(path.join(MF, 'models/jester/jester_kit.js'), 'utf8').split('\n');
  // lines a..b (1-based, inclusive); `starts` and `ends` pin the cut to the text it was made for
  function cut(a, b, starts, ends) {
    if (!L[a - 1].trim().startsWith(starts)) throw new Error(`jester_kit.js line ${a} is not "${starts}": the kit has changed, find the lines again`);
    if (ends != null && !L[b - 1].trim().startsWith(ends)) throw new Error(`jester_kit.js line ${b} is not "${ends}": the kit has changed, find the lines again`);
    return L.slice(a - 1, b).join('\n');
  }
  function rep(src, from, to, n) {
    const parts = src.split(from), want = n == null ? 1 : n;
    if (parts.length - 1 !== want) throw new Error('expected ' + want + ' of ' + JSON.stringify(from.slice(0, 90)) + ', found ' + (parts.length - 1));
    return parts.join(to);
  }

  let helpers = cut(9, 68, 'opts = opts || {};', 'const TEXS');
  // r186: a colour picture says so with colorSpace
  helpers = rep(helpers, 'if (srgb !== false) t.encoding = THREE.sRGBEncoding;', 'if (srgb !== false) t.colorSpace = THREE.SRGBColorSpace;');

  const skeleton = cut(81, 141, '// ---------- skeleton', '}');

  let motion = cut(1918, 2036, '// ---------- motion', '}');
  // the limb solver made four vectors a call (sixteen a frame): it now reuses its own
  motion = rep(motion, 'const d1 = V3().copy(_va)', 'const d1 = _s1.copy(_va)');
  motion = rep(motion, 'const mid = V3().copy(A).addScaledVector(d1, L.l1), end = V3().copy(A).addScaledVector(_va, d), d2 = end.sub(mid).normalize();', 'const mid = _s2.copy(A).addScaledVector(d1, L.l1), end = _s3.copy(A).addScaledVector(_va, d), d2 = end.sub(mid).normalize();');
  motion = rep(motion, 'const hz = V3().copy(hinge);', 'const hz = _s4.copy(hinge);');
  motion = rep(motion, '  // two-bone IK:', '  const _s1 = V3(), _s2 = V3(), _s3 = V3(), _s4 = V3();\n  // two-bone IK:');

  const waist = cut(2071, 2071, 'const _J = new THREE.Vector3();');
  const pose = cut(2073, 2174, '// ---------- applying a pose', '}');

  let anim = cut(3763, 3817, '// ---------- per-frame update', 'applyPose(P);');
  anim = rep(anim, "    spinHost = spinNow;                              // the turn the host has just given her root (last frame's spin)\n", '');
  anim = rep(anim, ', userWind = V3(0, 0, 0);', ';');
  // a hook between the base layer (idle, walk, run) and the one-shot move laid over it: the game carries tools, steers and swims here
  anim = rep(anim, "    let P = base; spinNow = 0;", "    if (opts.onBase) opts.onBase(base, t, dt);\n    let P = base; spinNow = 0;");
const out = `// GENERATED by src/people/port/rig.js from Moon Faire's game/models/jester/jester_kit.js. Do not edit by hand.
// The moving skeleton of Moon Faire's people, cut out of the kit that builds its Jester: bones, pose language, limb solver,
// idle / walk / run, one-shot moves and the blinking face. Her costume, cloth, spells and effects are left behind, and the
// body itself comes ready-made (folk/*.js). The code is the kit's own, line for line, apart from: three r186 colour spaces,
// a limb solver that no longer makes new vectors each frame, the opts.onBase hook, and the face painted only from pictures.
import * as THREE from 'three';

export function makeRig(opts) {
  ${helpers}

${skeleton}

  // ---------- bind: the meshes are bound to the skeleton as it rests; the upper body and the head shrink a little afterwards ----------
  const UPK = opts.upperScale || 0.97;             // scale of everything above the waist (applied to the first spine bone after the bind)
  const root = new THREE.Group(); root.name = 'person';
  root.add(SK.hips); root.updateMatrixWorld(true);
  const skeleton = new THREE.Skeleton(bones);
  SK.spine1.scale.setScalar(UPK); SK.head.scale.setScalar(opts.headScale || 0.98); root.updateMatrixWorld(true);

  // ---------- the face canvas: the painted face, with the eyes or the mouth of the moment set into it (a blink, an open mouth, a smile) ----------
  // opts.face: { base: a canvas or picture, parts: { shut, half, oh, smile: { src, x, y, w, h } } } (0..1 of the picture)
  const FACE = opts.face || null;
  const faceC = cvs(Math.round(1024 * TEXS), Math.round(1024 * TEXS)), faceT = ctex(faceC), faceState = { eyes: -1, mouth: '' };
  function paintFace(eyes, mouth) {
    const q = Math.round(eyes * 4) / 4;
    if (!FACE || (q === faceState.eyes && mouth === faceState.mouth)) return;
    faceState.eyes = q; faceState.mouth = mouth;
    const W = faceC.width, H = faceC.height, g = faceC.getContext('2d');
    g.drawImage(FACE.base, 0, 0, W, H);
    const put = (n) => { const r = FACE.parts[n]; if (r) g.drawImage(r.src, r.x * W, r.y * H, r.w * W, r.h * H); };
    if (q >= 0.75) put('shut'); else if (q >= 0.25) put('half');
    if (mouth === 'open') put('oh'); else if (mouth === 'smile') put('smile');
    faceT.needsUpdate = true;
  }
  paintFace(0, 'rest');

${motion}
${waist}
${pose}

${anim}
  }
  const state = {};
  return {
    root, skeleton, bones, SK, faceTexture: faceT, animate, play, defAction, FP, REST, state, hasAction: (n) => !!ACTS[n],
    stop() { act = null; pending = ''; },
    get busy() { return !!act && !(act.def.hold && act.t >= act.dur); }, get action() { return act ? act.type : ''; },
    get progress() { return act ? Math.min(1, act.t / act.dur) : -1; },
  };
}
`;
  fs.mkdirSync(path.join(OUT, 'kit'), { recursive: true });
  fs.writeFileSync(path.join(OUT, 'kit/rig.js'), out);
  return out.length;
};
