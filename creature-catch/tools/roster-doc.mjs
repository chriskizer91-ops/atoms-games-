// Writes docs/creature-catch-roster.md from the game data: stats, learnsets, moves.
//   node tools/roster-doc.mjs
import fs from 'node:fs';
import path from 'node:path';
import { loadData, SRC } from './load-data.mjs';

const CC = loadData();
const M = CC.MOVES;
const L = [];
const kindName = { starter1: 'Starter 1', starter2: 'Starter 2', starter3: 'Starter 3', base: 'Base', mid: 'Middle', final: 'Evolved', solo: 'Solo', legend: 'Legendary' };
const evoText = (e) => !e ? '' : typeof e.at === 'number' ? `${CC.CREATURES[e.into].name} at Lv ${e.at}` : `${CC.CREATURES[e.into].name} with ${e.at === 'sunshard' ? 'Sun Shard' : 'Moon Shard'}`;
const fxText = (fx) => {
  if (!fx) return '';
  const s = [];
  if (fx.status) s.push(`${fx.chance ? fx.chance + '% ' : ''}${fx.status}`);
  if (fx.stat) s.push(`${fx.chance ? fx.chance + '% ' : ''}${fx.self ? 'user' : 'target'} ${fx.stat} ${fx.stages > 0 ? '+' : ''}${fx.stages}`);
  if (fx.drain) s.push(`heals ${fx.drain * 100}% of damage`);
  if (fx.recoil) s.push(`${fx.recoil * 100}% recoil`);
  if (fx.heal) s.push(`heals ${fx.heal * 100}% HP`);
  if (fx.crit) s.push('high crit');
  if (fx.priority) s.push('goes first');
  if (fx.hits) s.push(`hits ${fx.hits[0]}${fx.hits[1] !== fx.hits[0] ? ' to ' + fx.hits[1] : ''} times`);
  if (fx.coins) s.push('your creature swipes extra coins if you win');
  return s.join(', ');
};

L.push('# Creature Catch: Roster, Stats and Movesets', '');
L.push('Generated by `node tools/roster-doc.mjs` from `src/js/10-12-data-*.js`. Change the data, not this file.', '');
L.push('## How the numbers are made', '');
L.push('- **Base total:** starters 210 / 330 / 450. Base forms of 2-stage lines 170 + 10 per region step (Grassland 190 up to Night Ruins 260). Evolved forms 1.6x their base. The vampire line is 240 / 340 / 450. Solo 195 + 16 per region step (Meadow 211 up to Night Ruins 339; Moonlynx +20).');
L.push('- **The final forms (v11, `src/js/12c-data-final.js`):** a creature that gained a form keeps its total. A new second form gets 1.6 times a first form\'s budget for its region; a new third form gets a third more than the form before it, at most 450. Crescub is 240. The family\'s creatures (`src/js/13b-family-creatures.js`) follow the same budgets by where they live.');
L.push('- **Shape:** the total is split over HP / Attack / Defense / Speed by a profile:');
L.push('');
L.push('| Profile | HP | Atk | Def | Spd |', '|---|---|---|---|---|');
for (const [k, w] of Object.entries(CC.PROFILES)) L.push(`| ${k} | ${w.join(' | ')} |`);
L.push('');
L.push('- **Stats at a level:** `HP = floor(2 x base x Lv / 100) + Lv + 10`, other stats `floor(2 x base x Lv / 100) + 5`.');
L.push('- **Learnset pattern:** Lv 1 Tackle + type basic (starters: Tackle + Growl, with their type basic at Lv 6, so the first rival fight is even), Lv 4 a stat buff, Lv 8 type utility, Lv 11 (starters) or 16 signature, Lv 12 second-type basic (or Growl), Lv 20 type strong, Lv 26 second-type strong (or Body Slam), Lv 34 another buff. Normal types: Tackle, Growl, buff, signature at 9, buff, Body Slam at 20. An evolved form keeps its line\'s moves and picks up its new type\'s moves on evolving. A wild creature knows its two newest attacks plus its newest other moves, up to 4.');
L.push('- **XP yield:** base total / 4, times the fainted creature\'s level / 5 (x1.5 against a trainer).', '');

L.push('## Creatures', '');
L.push('**Lives in** is the place its line is first met (the Creature Log\'s order). **Stat tier** is the region step its budget comes from. **Total** adds up the four stats; **Budget** is the total they are rounded from (and what the XP yield uses).', '');
L.push('| # | Creature | Type | Lives in | Stat tier | Stage | Profile | HP | Atk | Def | Spd | Total | Budget | Evolves | Signature |');
L.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
const zoneName = Object.fromEntries(CC.ZONES.map((z) => [z.key, z.name]));
CC.CREATURE_ORDER.forEach((id, i) => {
  const c = CC.CREATURES[id], b = c.base;
  L.push(`| ${i + 1} | ${c.name} | ${c.types.join(' / ')} | ${zoneName[CC.ZONE_OF[id]] || '-'} | ${c.region} (${CC.REGIONS[c.region] || '?'}) | ${kindName[c.kind]} | ${c.profile} | ${b.hp} | ${b.atk} | ${b.def} | ${b.spd} | ${b.hp + b.atk + b.def + b.spd} | ${c.total} | ${evoText(c.evo)} | ${M[c.sig].name} |`);
});
L.push('');

L.push('## Learnsets', '');
CC.CREATURE_ORDER.forEach((id) => {
  const c = CC.CREATURES[id];
  L.push(`**${c.name}** (${c.types.join(' / ')}): ` + c.learn.map(([lv, m]) => `${lv} ${M[m].name}`).join(', '));
  L.push('');
});

L.push('## Moves', '');
L.push('| Move | Type | Tier | Power | Acc | PP | Effect |', '|---|---|---|---|---|---|---|');
for (const [id, m] of Object.entries(M)) {
  if (id === 'struggle') continue;
  L.push(`| ${m.name} | ${m.type} | ${m.tier} | ${m.power || '-'} | ${m.acc || '-'} | ${m.pp} | ${fxText(m.fx)} |`);
}
L.push('', '**Struggle** (used when every move is out of PP): Power 30, no type, 25% recoil.', '');

L.push('## Wild spawns', '', 'In the order you reach each place (the same order the Creature Log numbers creatures in).', '');
const W = CC.SPAWN_WEIGHT;
L.push(`Each creature on a list turns up by its weight: common ${W.common}, uncommon ${W.uncommon}, rare ${W.rare}, unless the place sets its own (shown as a weight). A creature you have never met (in any form it can turn up as there) counts double. The level range is the place's, unless one is shown. A creature at or past its evolution level is met evolved. (\`CC.spawnTable\` in \`12-data-creatures.js\`, \`CC.rollSpawn\` in \`17-expansion.js\`.)`, '');
L.push('| Area | Levels | Common | Uncommon | Rare |', '|---|---|---|---|---|');
const nm = (s, t) => s[t].map((id) => {
  const extra = [s.weight && s.weight[id] != null ? `weight ${s.weight[id]}` : '', s.lv && s.lv[id] ? `Lv ${s.lv[id][0]} to ${s.lv[id][1]}` : '', (s.time || {})[id] || ''].filter(Boolean);
  return CC.CREATURES[id].name + (extra.length ? ` (${extra.join(', ')})` : '');
}).join(', ') || '-';
for (const z of CC.ZONES) for (const k of z.spawns) { const s = CC.SPAWNS[k]; L.push(`| ${s.name} | ${s.levels[0]} to ${s.levels[1]} | ${nm(s, 'common')} | ${nm(s, 'uncommon')} | ${nm(s, 'rare')} |`); }
L.push('');
L.push('### How often each one turns up', '', 'The share of encounters once you have met everything there (no new-creature bonus). In brackets: the forms it is met as, when it can be met evolved.', '');
L.push('| Area | By day | At night |', '|---|---|---|');
const odds = (k, night) => {
  const list = CC.spawnTable(k, night), sum = list.reduce((n, e) => n + e.w, 0), pc = (v) => (Math.round(v * 10) / 10) + '%';
  return list.map((e) => {
    const p = 100 * e.w / sum, n = e.levels[1] - e.levels[0] + 1, by = {};
    for (let lv = e.levels[0]; lv <= e.levels[1]; lv++) { const f = CC.wildForm(e.id, lv); by[f] = (by[f] || 0) + p / n; }
    const forms = Object.keys(by);
    return CC.CREATURES[e.id].name + ' ' + pc(p) + (forms.length > 1 || forms[0] !== e.id ? ' (' + forms.map((f) => CC.CREATURES[f].name + ' ' + pc(by[f])).join(', ') + ')' : '');
  }).join(', ');
};
for (const z of CC.ZONES) for (const k of z.spawns) L.push(`| ${CC.SPAWNS[k].name} | ${odds(k, false)} | ${odds(k, true)} |`);
L.push('');

const out = path.join(SRC, '..', 'docs', 'creature-catch-roster.md');
fs.writeFileSync(out, L.join('\n'));
console.log('wrote', out);
